#!/bin/bash
# Session Cleanup Script
# Runs at end of each session to archive working files and clean routes/ROOT

set -euo pipefail

PROJECT_ROOT="/workspace/app"
SESSION_ID="${1:-$(date +%Y%m%d_%H%M%S)}"
PROJECT_NAME="${2:-unknown}"
PROJECT_DIR="${PROJECT_ROOT}/projects/${PROJECT_NAME}"
ARCHIVE_DIR="${PROJECT_DIR}/archives/sessions/${SESSION_ID}"
ROUTES_DIR="${PROJECT_DIR}/routes"
ROOT_DIR="${PROJECT_DIR}/ROOT"

echo "=== Session Cleanup Started ==="
echo "Session ID: ${SESSION_ID}"
echo "Project: ${PROJECT_NAME}"
echo "Archive Dir: ${ARCHIVE_DIR}"

mkdir -p "${ARCHIVE_DIR}"
mkdir -p "${ROUTES_DIR}"
mkdir -p "${ROOT_DIR}"

# Archive routes folder if exists and has content
if [ -d "${ROUTES_DIR}" ] && [ "$(ls -A "${ROUTES_DIR}")" ]; then
    echo "Archiving routes folder..."
    (cd "${PROJECT_DIR}" && zip -r "${ARCHIVE_DIR}/routes_${SESSION_ID}.zip" "routes" -x "*.git*")
    echo "Routes archived to: ${ARCHIVE_DIR}/routes_${SESSION_ID}.zip"
    # Clean routes folder but keep directory
    find "${ROUTES_DIR}" -mindepth 1 -delete
    echo "Routes folder cleaned"
fi

# Archive ROOT folder if exists and has content
if [ -d "${ROOT_DIR}" ] && [ "$(ls -A "${ROOT_DIR}")" ]; then
    echo "Archiving ROOT folder..."
    (cd "${PROJECT_DIR}" && zip -r "${ARCHIVE_DIR}/ROOT_${SESSION_ID}.zip" "ROOT" -x "*.git*")
    echo "ROOT archived to: ${ARCHIVE_DIR}/ROOT_${SESSION_ID}.zip"
    # Clean ROOT folder but keep directory
    find "${ROOT_DIR}" -mindepth 1 -delete
    echo "ROOT folder cleaned"
fi

# Create session manifest
cat > "${ARCHIVE_DIR}/session_manifest.json" <<EOF
{
  "session_id": "${SESSION_ID}",
  "project_name": "${PROJECT_NAME}",
  "timestamp": "$(date -Iseconds)",
  "archives": [
    "routes_${SESSION_ID}.zip",
    "ROOT_${SESSION_ID}.zip"
  ],
  "notes": "Auto-generated by session_cleanup.sh"
}
EOF

echo "Session manifest created: ${ARCHIVE_DIR}/session_manifest.json"
echo "=== Session Cleanup Complete ==="